#!/usr/bin/env bash
# File the conformance-audit findings as GitHub issues.
#
# Usage:
#   ./file-conformance-audit-issues.sh              # dry run: print what would be filed
#   ./file-conformance-audit-issues.sh --apply      # actually create the issues
#   REPO=owner/name ./file-conformance-audit-issues.sh --apply
#
# Requires: gh (authenticated) for --apply; the dry run needs nothing.
# Idempotent: an issue whose exact title already exists (open or closed) is skipped.
# Labels that don't exist on the repo are dropped with a warning rather than failing.

set -euo pipefail

REPO="${REPO:-cerbos/query-plan-adapters}"
APPLY=false
[[ "${1:-}" == "--apply" ]] && APPLY=true

if $APPLY; then
  command -v gh >/dev/null || { echo "gh is required" >&2; exit 1; }
  gh auth status >/dev/null 2>&1 || { echo "run 'gh auth login' first" >&2; exit 1; }
  EXISTING_LABELS="$(gh label list --repo "$REPO" --limit 500 --json name --jq '.[].name')"
  EXISTING_TITLES="$(gh issue list --repo "$REPO" --state all --limit 1000 --json title --jq '.[].title')"
else
  echo "DRY RUN against $REPO — pass --apply to create issues."
  EXISTING_LABELS=""
  EXISTING_TITLES=""
fi

FOOTER=$'\n\n---\n_Found in a static audit of the conformance harnesses. Generated by [Claude Code](https://claude.ai/code)_'

created=0; skipped=0

# file_issue "<title>" "<comma-separated labels>"  (body on stdin)
file_issue() {
  local title="$1" labels="$2" body
  body="$(cat)${FOOTER}"

  if ! $APPLY; then
    printf '\n=== %s\n    labels: %s\n' "$title" "$labels"
    printf '%s\n' "$body" | sed 's/^/    | /'
    return
  fi

  if grep -Fxq -- "$title" <<<"$EXISTING_TITLES"; then
    echo "skip (exists): $title"; skipped=$((skipped + 1)); return
  fi

  local args=() l
  IFS=',' read -ra wanted <<<"$labels"
  for l in "${wanted[@]}"; do
    if grep -Fxq -- "$l" <<<"$EXISTING_LABELS"; then
      args+=(--label "$l")
    else
      echo "  warning: label '$l' not on $REPO, dropping" >&2
    fi
  done

  local url
  url="$(gh issue create --repo "$REPO" --title "$title" --body "$body" "${args[@]}")"
  echo "created: $url"
  created=$((created + 1))
}

