file_issue "mongoose, convex: unmapped attributes fall through as raw field paths, so \$ne matches every document" "needs-triage,mongoose,convex" <<'EOF'
## Problem

An attribute with no mapper entry is used verbatim as a field path:

- mongoose: `mongoose/src/mapper.ts` returns `{ path: [reference] }`; `mapper` defaults to `{}`; `nullable` defaults to false.
- convex: `resolveField` in `convex/src/operands.ts` returns the reference verbatim; `isNullableField` defaults to false, and such a field passes `canPushToDb`.

So `R.attr.status != "x"` with a missing or typo'd mapping becomes `{"request.resource.attr.status": {$ne: "x"}}` (or `q.neq(q.field(...), "x")`). The path doesn't exist, `$ne` matches absent fields, and **every document is returned**. `not` via `$nor` has the same problem on any non-`nullable` field that can be absent.

langchain-chromadb is the counter-example: it defaults `required: false` and refuses `$ne`/`$nin` unless the field is declared required.

The corpus can't catch this — every harness maps every field correctly with `nullable` set.

## Proposal

Fail closed: throw on an unmapped reference (or require an explicit pass-through opt-in), and/or default `nullable` to true. Add unit tests for mapping variation (unmapped field, absent field) under the "caller-supplied argument" category.
EOF

file_issue "mongoose: nullAttributeRepresentation \"omitted\" doesn't guard ne/not/nin on absent fields" "needs-triage,mongoose" <<'EOF'
## Problem

`nullAttributeRepresentation: "omitted"` only rejects **null literals** (`assertNullOperandTranslatable`, `mongoose/src/context.ts`). It does not guard `ne` / `not` / `nin` over a field that is NULL or absent and not declared `nullable`.

Under the omitted convention, `R.attr.x != "a"` on such a field makes `check()` raise a missing-attribute error (deny), while `$ne` matches the document — an over-grant. `mongoose/README.md` (~line 87) calls the option "the backstop for mappings that do not declare it", which overstates what it does.

## Proposal

Under `"omitted"`, reject (or null-guard) negated comparisons over fields not declared `nullable`, or correct the README so callers don't rely on it as a backstop. Also consider testing `strictQuery: true`, which strips unknown paths and can turn a filter into `{}`.
EOF

file_issue "Result types let a caller that skips the kind check fail open" "needs-triage,mongoose,langchain-chromadb,convex,ent,pgx" <<'EOF'
## Problem

Several adapters return a result where using the filter without first switching on `kind` returns every row on a denial:

- **mongoose**: `QueryPlanToMongooseResult` is `{ kind, filters? }`, not a discriminated union. On `ALWAYS_DENIED`, `filters` is undefined, and `Model.find(undefined)` returns everything.
- **langchain-chromadb**: `where: undefined` on a denial means all documents.
- **convex**: once `allowPostFilter` is on, nothing in the types forces the caller to apply `postFilter` as well as `filter`; applying `filter` alone over-grants.
- **ent**: `Result.Predicate` is nil for `ALWAYS_DENIED` (and error paths); `s.Where(nil)` leaves WHERE unset. The zero-value `Kind` is `KindAlwaysDenied` and the README/example switch on `Kind`, which mitigates it.
- **pgx**: `Where == ""` on a denial; a builder that skips an empty WHERE over-grants (the example asserts the splice is a syntax error, which helps).

All are documented as "check the kind first", but the types don't enforce it.

## Proposal

Make denial fail closed in the value itself: a discriminated union in TypeScript, a deny-everything filter/predicate (`1 = 0`, `{_id: {$in: []}}`, etc.) instead of undefined/nil/empty, and a combined convex result that can't be half-applied.
EOF

file_issue "prisma: empty and/or becomes {AND: []}, and relation-element nullable is opt-in" "needs-triage,prisma" <<'EOF'
## Problem

1. **Empty boolean operators.** `buildPrismaFilterFromCerbosExpression` (`prisma/src/translate.ts`) maps `and` to `{ AND: operands.map(...) }` with no arity check. An empty `and` becomes `{AND: []}`, which matches everything; an empty `or` becomes `{OR: []}`. drizzle (`filter.ts`) and activerecord throw in the same case. The planner doesn't emit this today, so it's hardening, but it should fail closed. Hierarchy code also returns `{}` in places (`hierarchy.ts`); `{NOT: {}}` under negation is untested.
2. **`nullable` on relation element columns is opt-in** (`prisma/src/index.ts`). Leaving it off a column that can be NULL drops the NULL guard on negated `exists`, `all` and `hasIntersection`-over-`map`, which then return rows with a NULL element the PDP denies. The corpus always declares `nullable: true`, and `prisma/README.md` presents it as a feature, not a hazard.

## Proposal

Throw on zero-operand `and`/`or`; pin `{NOT: {}}` behaviour; consider defaulting relation-element `nullable` to true (or documenting the omission as an over-grant hazard).
EOF

file_issue "elasticsearch-java: type-mismatch guard only runs for fields declared via withScalarTypes" "needs-triage,elasticsearch-java" <<'EOF'
## Problem

`typeMismatchQuery` in `LeafTranslator.java` returns early when the field has no entry in `options.scalarTypes()`. With default options, `R.attr.aNumber == "5"` becomes a `term` query; Elasticsearch coerces `"5"` onto the numeric field and matches it. CEL says false and `check()` denies, so rows the PDP denies are returned.

The corpus runs only with `withScalarTypes` declared (`Corpus.java`), so the default is never oracle-compared. The README hazard row says the adapter "cannot see the mapping" but doesn't point at `withScalarTypes` as the fix.

Related, caller-owned: mapping a string to an analyzed `text` field instead of `keyword` makes `term`/`prefix` match per token and case-insensitively. It's measured in `ElasticsearchSurfaceTest` and documented, but fails silently at runtime.

## Proposal

Either require scalar types (fail closed on an undeclared field used in a scalar comparison) or document `withScalarTypes` prominently as required for correctness.
EOF

file_issue "drizzle: SQLite timestamp literals compare as text without checking the column's type" "needs-triage,drizzle" <<'EOF'
## Problem (suspected — found statically, needs confirming against a real SQLite table)

`valueType: "timestamp"` binds the literal as a normalised RFC 3339 string, stripping a `.000` fraction (`drizzle/src/values.ts`, `normalizeRfc3339Milliseconds`). The column's `dataType` is never checked.

- A text column holding JS `toISOString()` values (`…00.000Z`) compares lexically. Since `'.' < 'Z'`, `timestamp(col) < timestamp("…00Z")` is TRUE at an equal instant — an over-grant.
- For an integer-mode timestamp column, SQLite orders integer < text, so `<` matches every row.

The corpus has the witness (a1 `updatedAt = "…00.000Z"`) but only the field-to-field action reads it, and that action is refused. The ordered thresholds never fall between two spellings of the same instant.

## Proposal

Add a corpus action with a threshold at an instant whose stored spelling differs from the canonical one; check the column's `dataType`/mode in the translator and refuse (or normalise) where the comparison would be lexical.
EOF

file_issue "sqlalchemy: SQLite LIKE pragma undocumented, README overrides untested, empty and_/or_ passes through" "needs-triage,sqlalchemy" <<'EOF'
## Problem

1. **`PRAGMA case_sensitive_like` is not in the README.** The harness sets it (`tests/test_adversarial_conformance.py`); it appears only in a code comment in `_operators.py`. A column collation doesn't change SQLite's LIKE, so a SQLite consumer following the README gets case-insensitive `contains`/`startsWith`/`endsWith` — an over-grant. (`activerecord/README.md` documents the pragma.)
2. **Relation macros are proven against test-only overrides.** `exists`, `all`, `exists_one`, `filter`, `map`, `size`, `hasIntersection`, `in` over related tables come from `OPERATOR_OVERRIDES` in `tests/corpus.py`, not shipped code. Those handle three-valued logic carefully (e.g. `_exists_fn`'s `body.is_(None) → null()` arm). The README's copy-paste overrides are simpler and nothing runs them against the oracle.
3. **Empty `and`/`or`.** `predicate` in `_translator.py` passes `and_(*[])` / `or_(*[])` straight through; an empty `or_()` should be FALSE but can render as an empty clause that `where()` drops. The planner doesn't emit this; activerecord refuses it explicitly.

## Proposal

Document the pragma; either ship the relation overrides as library helpers or run the README's examples through the oracle; throw on zero-operand `and`/`or`.
EOF

file_issue "Default nullAttributeRepresentation is \"explicit\", the permissive convention" "needs-triage,prisma,drizzle,mongoose,sqlalchemy,activerecord,ent,pgx" <<'EOF'
## Problem

Across these adapters, the null-convention option defaults to `explicit` (e.g. `prisma/src/index.ts`, `drizzle/src/index.ts`, `ent/adapter.go`). An application that *omits* NULL attributes from `check()` but keeps the default gets `== null` rendered as `IS NULL`, returning rows the PDP denies. The harnesses demonstrate this deliberately (`null-eq-missing`).

On ent/pgx the harness itself runs with several NULL-able columns (`scope`, `aDouble`, `createdAt`, `updatedAt`, `parent.*`) left at `NullConventionUnset` while its oracle omits their NULLs (`ent/adversarial_test.go`). No current action reaches that combination (e.g. `R.attr.scope == null`), so it's latent rather than failing.

## Proposal

Decide whether the default should be the fail-closed choice (`omitted`, which refuses null-selecting shapes), or require callers to choose explicitly. At minimum, add a corpus action that probes `== null` on a harness column left at the default, so the latent case is exercised.
EOF

