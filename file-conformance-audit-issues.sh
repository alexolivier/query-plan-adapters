file_issue "conformance: corpus never plans the root shapes real policies compose to (ALLOW+DENY, multiple ALLOWs)" "needs-triage,conformance" <<'EOF'
## Problem

`conformance/policies/adversarial.yaml` has ~302 rules, **all `EFFECT_ALLOW`**, one role (`USER`), one principal (`u1`), no derived roles, variables or scoped policies. Walking every fixture in `conformance/wire-fixtures/`:

- No root is `and(X, not(Y))` — what a conditional ALLOW plus a conditional DENY composes to.
- No root is `or(and(...), and(...))` — what several conditional ALLOW rules compose to.
- The root `and` fixtures (`filter-as-conjunct`, `nary-and`, `pv-all-unrolled`, `rel-hop-and-root`, `rel-range-hop`) carry no `not` conjunct.
- `and → not` / `or → and` nesting appears only inside `p-deep-nest`, which prisma, mongoose, langchain-chromadb and elasticsearch-java refuse — so for those adapters a negation under a conjunction is never oracle-compared.

`conformance/README.md` ("Hazard classes the corpus missed") says `not-and` is byte-for-byte what a DENY rule composes to. That only holds for a DENY whose condition is `a && b` beside an unconditional ALLOW.

The planner's own composition logic (multiple rules, DENY, derived roles with resource conditions, variables) is never exercised against resource attributes. `evaluation-probe.yaml` has DENY rules and a derived role, but only over principal attributes, so its plans are unconditional. A second planner fold bug like `p-has` would go unnoticed.

## Why it matters

Adapters that special-case the root (convex's DB/post-filter split; the root-only guards `filter-as-conjunct` already caught) are exactly where a composed plan could slip through as an over-grant.

## Proposal

- Add actions whose plans root at `and(X, not(Y))`, `or(and, and)` and `or(X, not(Y))`.
- Add a second resource kind (or policy) with real conditional DENY rules, a derived role with a resource condition, and variables, so the planner's composition output is captured in wire fixtures and compared by every harness.
EOF

file_issue "conformance: aString, aNumber and aBool are never NULL in any seed" "needs-triage,conformance" <<'EOF'
## Problem

In `conformance/seeds.json` (27 seeds), `aString`, `aNumber` and `aBool` are null/absent in **0** rows. NULL witnesses exist only for `aOptionalString` (5 rows), the derived fields and relations.

These are the most-read columns in the corpus (roughly 73 / 56 / 33 fixtures respectively), and dozens of those actions negate (`not`, `ne`). So `!R.attr.aBool`, `R.attr.aNumber != 5`, `!(R.attr.aString == "x")` etc. are never compared against a NULL/missing row — the classic three-valued-logic over-grant this corpus exists to catch. On document stores, `$ne`/`$nor` additionally match documents where the field is absent.

A concrete case already parked in a unit test for want of this: `string(nullBoolColumn) != "true"` (`ent/translate_test.go` / `pgx/translate_test.go`, `TestStringOverABooleanSpellsCELsWords`, bridge tracked by #469).

## Proposal

Add seeds with NULL/missing `aString`, `aNumber`, `aBool` (plus their `derived-fields.json` entries), re-run every harness, and triage divergences per CLAUDE.md "Changing how a condition is translated". Retire the #469 bridge once the corpus carries it.
EOF

file_issue "conformance: no action orders a string column (collation-dependent over-grant)" "needs-triage,conformance" <<'EOF'
## Problem

The only `<`/`>` against a string attribute in `conformance/policies/adversarial.yaml` is the NaN probe (~line 2957). A plain `R.attr.aString > "a"` is never planned.

CEL orders strings by bytes. Adapters emit a plain SQL `<`/`>`, whose result depends on collation. SQLite's default (BINARY) agrees with CEL; PostgreSQL with a locale collation (e.g. `en_US.UTF-8`) does not — `'A' > 'a'` is true there and false in CEL, which returns rows the PDP denies.

The README collation sections (e.g. `sqlalchemy/README.md`, `activerecord/README.md`) cover equality, membership and LIKE, but not ordering.

## Proposal

Add string-ordering actions with case- and accent-discriminating seeds, run them on every store leg (including PostgreSQL under a locale collation to measure the cost, as `ADAPTER_TEST_MYSQL_COLLATION` does for MySQL), and document ordering in each README's collation section.
EOF

file_issue "conformance: assert a non-total oracle for every compared action, not a sample" "needs-triage,conformance,mongoose,convex,prisma,drizzle,ent,pgx" <<'EOF'
## Problem

The degeneracy guard (`conformance/README.md`, "The degeneracy guard") asks for "a handful of representative actions". Several harnesses guard only a sample of what they compare:

| Adapter | Guarded / compared (approx.) |
|---|---|
| ent, pgx | 86 / 235 |
| mongoose | 72 / 202 |
| convex | 105 / 269 |
| prisma | 123 / 172 |
| drizzle | 119 / 236 |

elasticsearch-java, spring-data and langchain-chromadb already guard (nearly) every compared action.

An empty oracle still catches an over-grant (equality fails), but a **total** oracle cannot: an adapter that returns every row passes. For an unguarded action nothing asserts the oracle is non-total. Some are total by construction (`pv-empty-not-exists`, `pv-empty-all`, `ne-map`), which is fine only if listed.

## Proposal

Assert non-total for every oracle-compared action, with an explicit, corpus-level allowlist of actions that are total (or empty) by construction, each with a reason. That also removes the per-harness list drift the README warns about.
EOF

file_issue "conformance: p-has is a live over-grant — link upstream and pin the composed form" "needs-triage,conformance" <<'EOF'
## Problem

`knownDivergences` excludes `p-has` for every adapter: the planner folds `has(R.attr.aOptionalString)` to `KIND_ALWAYS_ALLOWED`, so every adapter returns every row while `check()` denies rows missing the attribute. This is a production over-grant for any consumer whose policy uses `has()`, not a test artifact.

- The `actions.json` entry has no `relatedIssue` / upstream Cerbos link.
- Each adapter README mentions it in one table row; only `spring-data/README.md` gives it a section.
- Only the bare root form is pinned. The composed form — `has(x) && y == 1` silently losing its `has` guard — is not.

## Proposal

- File (or link) the upstream `cerbos/cerbos` planner issue and set `relatedIssue`.
- Add a composed action (`has(x) && <other condition>`) so the tripwire covers the form real policies use.
- Give it a prominent warning in each adapter README rather than a table row.
EOF

