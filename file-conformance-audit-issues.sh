file_issue "CI doesn't run the corpus on the production stores for sqlalchemy, activerecord and spring-data/Hibernate 7" "needs-triage,sqlalchemy,activerecord,spring-data" <<'EOF'
## Problem

CLAUDE.md: "a store the workflow does not execute is a store the adapter does not cover." Current gaps:

- **sqlalchemy**: all ~242 compared actions run on SQLite (1.4 and 2.x). PostgreSQL runs only the ~21 actions that read a `collection_columns` declaration. MySQL never runs. The PostgreSQL golden SQL is compiled, not executed.
- **activerecord**: SQLite only (`spec/support/database.rb`), and only on AR 8.0 (`.github/workflows/activerecord.yaml`). The MySQL/PostgreSQL branches in `lib/cerbos/active_record/dialect.rb` (`CONCAT`, `CHAR_LENGTH`, `double precision`, …) never execute. (7.1's golden divergence list is pinned empty, so the version gap is small; the store gap is the real one.)
- **spring-data**: H2 runs on Hibernate 6.6 and 7; PostgreSQL and MySQL run only on the baseline ORM. Hibernate 7 × PostgreSQL/MySQL is never exercised.

## Proposal

Add store legs (testcontainers, as drizzle/prisma/ent do) running the full corpus: PostgreSQL and MySQL for sqlalchemy and activerecord; Hibernate 7 × PostgreSQL/MySQL for spring-data. Pin collations as the existing MySQL legs do.
EOF

